const catalog: NameEty[] = rows.map(([name, meaning, strong]) => ({ name, meaning, strong }))

function fold(value: string) {
  return value.normalize("NFC").toLowerCase().replace(/[^a-z]/g, "")
}

const byKey = new Map(catalog.map((item) => [fold(item.name), item]))

export const hitchcockNames = catalog

export const hitchcockFeatured = ["Adam", "Eve", "Abraham", "Moses", "David", "Israel", "Jerusalem", "Jesus", "Mary", "Peter"]

export function findHitchcock(query: string, limit = 12): NameEty[] {
  if (/^[hg]\s*\d+$/i.test(query.trim())) return []
  const needle = fold(query)
  if (!needle) return []
  const exact = byKey.get(needle)
  if (exact) return [exact]
  if (needle.length < 3) return []
  const hits: NameEty[] = []
  for (const item of catalog) {
    if (fold(item.name).includes(needle) || fold(item.meaning).includes(needle)) hits.push(item)
    if (hits.length >= limit) break
  }
  return hits
}

export function hitchcockForGloss(text: string, limit = 4): NameEty[] {
  const words = text.match(/[A-Za-z']{3,}/g) ?? []
  const hits: NameEty[] = []
  const seen = new Set<string>()
  for (const word of words) {
    const item = byKey.get(fold(word))
    if (!item || seen.has(item.name)) continue
    seen.add(item.name)
    hits.push(item)
    if (hits.length >= limit) break
  }
  return hits
}
