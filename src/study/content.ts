let crossIndex: Record<string, string[]> | null = null

export function setCrossIndex(index: Record<string, string[]>) {
  crossIndex = index
}

export function linksFor(book: number, chapter: number, verse: number) {
  const key = `${book}:${chapter}:${verse}`
  const ranked = crossIndex?.[key]
  if (ranked?.length) return ranked
  return links[key] ?? []
}

export function dayOfYear(date = new Date()) {
  const start = Date.UTC(date.getFullYear(), 0, 0)
  const today = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate())
  return Math.floor((today - start) / 86_400_000)
}

export function passageForDay(date = new Date()) {
  const index = (dayOfYear(date) - 1 + dailyPassages.length) % dailyPassages.length
  return dailyPassages[index]
}

